#!/usr/bin/env node
/* Keep deleted assets dead. Run by tools/deploy.sh after the build, before check-site:
 *   node tools/retire-assets.mjs
 * 1. Every file in the last release (tools/released.json "files") that public/ no longer has is added to
 *    tools/retired-assets.txt (pages and the Pages config files aside).
 * 2. Refuse any retired name reintroduced into public/; names stay burned forever.
 * 3. The block between the markers in public/_redirects is rewritten from the list: one "<path> /404.html 404" rule each.
 * 4. functions/retired.js is rewritten: the list, and the headers the middleware's retired 404 sends.
 * Cloudflare Pages kept serving deleted assets on the custom domain, and only the middleware answers before its cache. */
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..'), pub = path.join(root, 'public');
const listFile = path.join(root, 'tools/retired-assets.txt'), redirectsFile = path.join(pub, '_redirects');
const BEGIN = '# BEGIN retired assets (generated by tools/retire-assets.mjs from tools/retired-assets.txt; edit the list, not this block)';
const END = '# END retired assets';
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
const current = new Set(walk(pub).map((f) => '/' + path.relative(pub, f).split(path.sep).join('/')));
const asset = (p) => !p.endsWith('.html') && !['/_headers', '/_redirects', '/_routes.json', '/sitemap.xml'].includes(p);

const text = fs.readFileSync(listFile, 'utf8'), head = text.split('\n').filter((l) => l.startsWith('#'));
const list = new Set(text.split('\n').filter((l) => l.startsWith('/')));
const released = fs.existsSync(path.join(root, 'tools/released.json')) ? JSON.parse(fs.readFileSync(path.join(root, 'tools/released.json'), 'utf8')) : {};
let added = 0;
for (const p of released.files || []) if (asset(p) && !current.has(p) && !list.has(p)) { list.add(p); added++; console.log(`retired: ${p} (in ${released.version}, gone now)`); }
const reused = [...list].filter(p => current.has(p));
if (reused.length) throw new Error('Burned asset names cannot be reused: ' + reused.join(', '));
if (!released.files) console.log('tools/released.json has no file list yet; the next release records one');
const sorted = [...list].sort();
fs.writeFileSync(listFile, head.join('\n') + '\n' + sorted.join('\n') + '\n');

const red = fs.readFileSync(redirectsFile, 'utf8');
const block = [BEGIN, ...sorted.map((p) => `${p} /404.html 404`), END].join('\n');
const i = red.indexOf(BEGIN), j = red.indexOf(END);
const next = i >= 0 && j > i ? red.slice(0, i) + block + red.slice(j + END.length) : red.replace(/\n*$/, '\n\n') + block + '\n';
fs.writeFileSync(redirectsFile, next);
// 4. functions/retired.js: the list for the middleware, plus the headers its 404 sends (the site's own, from the /* rule
//    in public/_headers, with no-store, no-transform), so the Function can't drift from either
const glob = [], lines = fs.readFileSync(path.join(pub, '_headers'), 'utf8').split('\n');
for (let i = lines.indexOf('/*') + 1; i < lines.length && /^\s+\S/.test(lines[i]); i++) {
  const [k, ...v] = lines[i].trim().split(':');
  if (!/^(cache-control|cloudflare-cdn-cache-control)$/i.test(k)) glob.push([k, v.join(':').trim()]);
}
const headers = Object.fromEntries([...glob, ['Content-Type', 'text/plain; charset=utf-8'], ['Cache-Control', 'no-store, no-transform']]);
fs.writeFileSync(path.join(root, 'functions/retired.js'), '// Generated by tools/retire-assets.mjs from tools/retired-assets.txt and the /* rule in public/_headers. Don\'t edit.\n'
  + 'export const RETIRED = new Set(' + JSON.stringify(sorted, null, 1) + ');\n'
  + 'export const HEADERS = ' + JSON.stringify(headers, null, 1) + ';\n');
console.log(`retired assets: ${sorted.length}${added ? ` (${added} new)` : ''}; _redirects block and functions/retired.js rewritten`);
